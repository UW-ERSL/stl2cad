def node_plane(sw, k, pt, name, checked=True):
    """Plane parallel to the Right Plane through the joint's skeleton point; else offset from the Right Plane.
    Unchecked (FAST_PLANES): the node sketch on it checks it."""
    p = JOINTS[k]
    check = (lambda f: (lambda r: (r[0], f"{r[1]:+.4f} mm off"))(plane_through(sw, f, p, (1.0, 0.0, 0.0)))) \
        if checked else (lambda f: (True, ""))

    def sel():
        sd = call0(sw.model.SelectionManager, "CreateSelectData"); sd.Mark = 0
        sd1 = call0(sw.model.SelectionManager, "CreateSelectData"); sd1.Mark = 1
        f = sw.model.FeatureByName("Right Plane")
        return f.Select2(False, 0) and pt.Select4(True, sd1)
    f, note = plane_by(sw, sel, ("parallel through the joint", (REF_PARALLEL, 0, REF_COINC, 0, 0, 0)), check, name)
    if f is not None:
        return f, True
    print(f"  {name}: {note}; offset from the Right Plane instead")
    return offset_plane(sw, "Right Plane", p[0], p, name), False


def node3_step(sw, st, drift, made, skel):
    """Sphere: a semicircle (top to bottom through +z) closed by a line along y, revolved about the line."""
    live_skeleton(sw, skel)
    k = st["joint"]
    x, y, z = JOINTS[k]
    r = st["r"]
    plane, follows = node_plane(sw, k, skel["points"][k], st["name"] + " plane", checked=not FAST_PLANES)
    fm = sw.model.FeatureManager
    v, cc = expected(st, drift)
    check_now = due(st)
    first = True
    for variant in (("line", 16), ("line", 4), ("centerline", None), ("centerline", 4), ("centerline", 16)):
        snap = (sw.dims_ok, len(sw.linkable), len(sw.alldims), sw.rels_ok, len(sw.status), len(sw.rels_failed))
        try:
            sm, T, h = sketch_on(sw, plane, (x, y, z), st["name"], (1.0, 0.0, 0.0), 1 if (FAST_PLANES and first) else 4)
        except OffPlane as ex:
            if not (FAST_PLANES and first):
                raise
            print(f"  {st['name']} plane: {ex}; made again with the check")
            sw.model.ClearSelection2(True); plane.Select2(False, 0); sw.model.Extension.DeleteSelection2(0)
            plane, follows = node_plane(sw, k, skel["points"][k], st["name"] + " plane", checked=True)
            sm, T, h = sketch_on(sw, plane, (x, y, z), st["name"], (1.0, 0.0, 0.0))
        if first:
            made["planes"].append(plane)
        first = False
        Qs = lambda p: to_sk(T, p)
        C, top, bot, side = Qs((x, y, z)), Qs((x, y + r, z)), Qs((x, y - r, z)), Qs((x, y, z + r))
        arc = make(sm.CreateArc, C[0], C[1], 0.0, top[0], top[1], 0.0, bot[0], bot[1], 0.0, arc_turn(top[:2], side[:2], bot[:2]))
        ln = make(sm.CreateLine, bot[0], bot[1], 0.0, top[0], top[1], 0.0)
        axis = ln
        if variant[0] == "centerline":
            e0, e1 = Qs((x, y - r - 1.0, z)), Qs((x, y + r + 1.0, z))
            axis = make(sm.CreateCenterLine, e0[0], e0[1], 0.0, e1[0], e1[1], 0.0)
        sm.AddToDB = False
        if DIMENSION and variant[0] == "line":
            P = sketch_points(sm)
            oc = at(P, C)
            if oc:
                nf = len(sw.rels_failed)
                rel(sw, "sgCOINCIDENT", [oc[0], skel["points"][k]], f"{st['name']}: centre at its joint")
                if len(sw.rels_failed) > nf:          # not at the joint: centre dimensioned from the origin
                    if abs(C[0]) > 1e-7:
                        dim(sw, [oc[0]], "H", (C[0] / 2, C[1] - 0.004), f"{st['name']}: centre {axis_name(T, 0)}", origin=True)
                    if abs(C[1]) > 1e-7:
                        dim(sw, [oc[0]], "V", (C[0] - 0.004, C[1] / 2), f"{st['name']}: centre {axis_name(T, 1)}", origin=True)
                rel(sw, "sgHORIZONTAL2D" if abs(top[1] - bot[1]) < 1e-7 else "sgVERTICAL2D", [ln], f"{st['name']}: axis line")
                rel(sw, "sgCOINCIDENT", [oc[0], ln], f"{st['name']}: centre on the axis line")
                txt = (side[0] + 0.5 * (side[0] - C[0]) + 0.001, side[1] + 0.5 * (side[1] - C[1]) + 0.001)
                dim(sw, [arc], "any", txt, f"{st['name']}: node radius")
                join_ends(sw, sm, [top, bot], st["name"])
            else:
                sw.dims_failed.append(f"{st['name']}: node centre not found")
        sk = close_sketch(sw, sm, h, st["name"] + " node")
        sw.model.ClearSelection2(True)
        sk.Select2(False, 0)
        if variant[1] is not None:
            sd = call0(sw.model.SelectionManager, "CreateSelectData"); sd.Mark = variant[1]
            axis.Select4(True, sd)
        f = fm.FeatureRevolve2(True, True, False, False, False, False, 0, 0, 2 * math.pi, 0.0,
                               False, False, 0.0, 0.0, 0, 0.0, 0.0, True, True, True)
        if f is not None and not check_now:
            f.Name = st["name"]
            made["sketches"].append(sk)
            print(f"{st['name']}: node (checked with a later feature)")
            return
        if f is not None:
            vv, c2 = checked_mass(sw, v, tol(st))
            if abs(vv - v) <= tol(st) and math.dist(c2, cc) <= 1e-4 * SIZE + 1e-2 + 1e-3 * PENDING["n"]:
                f.Name = st["name"]
                done_check(st)
                made["sketches"].append(sk)
                print(f"{st['name']}: node, volume {vv:.3f} mm^3 (expected {v:.3f})"
                      + ("" if variant == ("line", 16) else f" (revolve about the {variant[0]}, Mark {variant[1]})")
                      + ("" if follows else " (plane not attached to the joint)"))
                carry(drift, vv, c2, v, cc)
                return
            print(f"  {st['name']}: revolve about the {variant[0]} (Mark {variant[1]}) gave volume {vv:.3f} mm^3, expected {v:.3f}")
            sw.model.ClearSelection2(True); f.Select2(False, 0); sw.model.Extension.DeleteSelection2(0)
        else:
            print(f"  {st['name']}: revolve about the {variant[0]} (Mark {variant[1]}) returned no feature")
        sw.model.ClearSelection2(True); sk.Select2(False, 0); sw.model.Extension.DeleteSelection2(0)
        sw.dims_ok, sw.rels_ok = snap[0], snap[3]
        del sw.linkable[snap[1]:], sw.alldims[snap[2]:], sw.status[snap[4]:], sw.rels_failed[snap[5]:]
        sw.under = [u for u in getattr(sw, "under", []) if not u.startswith(st["name"] + " node")]
    raise RuntimeError(f"{st['name']}: no revolve gives the expected node")


def hub3_step(sw, st, drift, made):
    """Hub (boss, radius ro) or hole (cut, radius ri): a circle on a plane offset from the standard plane normal to
    the hub's axis, at the hub's end away from that plane, extruded over the hub's length."""
    n = st["hub"]
    h = HUBS[n]
    k = h["axis"]
    level = h["lo"] if abs(h["lo"]) > 1e-9 else h["hi"]
    plane = offset_plane(sw, STD[k], level, axis_point(h, level), st["name"] + " plane")
    made["planes"].append(plane)
    r = h["ro"] if st["kind"] == "hub" else h["ri"]
    sm, T, hp = sketch_on(sw, plane, axis_point(h, level), st["name"])
    C = to_sk(T, axis_point(h, level))
    circ = make(sm.CreateCircleByRadius, C[0], C[1], 0.0, r * MM)
    sm.AddToDB = False
    if DIMENSION:
        oc = at(sketch_points(sm), C)
        if oc:
            lab = (f"joint hub axis {h['line']} {axis_name(T, 0)}", f"joint hub axis {h['line']} {axis_name(T, 1)}")
            if abs(C[0]) > 1e-7:
                dim(sw, [oc[0]], "H", (C[0] / 2, C[1] - 0.004), lab[0], origin=True)
            if abs(C[1]) > 1e-7:
                dim(sw, [oc[0]], "V", (C[0] - 0.004, C[1] / 2), lab[1], origin=True)
        dim(sw, [circ], "any", (C[0] + 0.7 * r * MM, C[1] + 0.7 * r * MM), f"{st['name']}: diameter")
    sk = close_sketch(sw, sm, hp, st["name"])
    v, c = expected(st, drift)
    fast, sw.mass = sw.mass, sw.mass_rebuilt    # the direction is chosen by the volume: rebuilt values here
    try:
        vv = sw.feature(sk, "add" if st["kind"] == "hub" else "cut", 0.0, h["hi"] - h["lo"], v, c, st["name"])
        carry(drift, *sw.mass(), v, c)
    finally:
        sw.mass = fast


def bar3_step(sw, st, drift, made, skel):
    """Bar: Loft through circles on planes normal to its spline at the kept joints, the spline as centerline
    (sw_probe_bars: the radius then changes linearly with the arc length between sections, as the reference)."""
    live_skeleton(sw, skel)
    n = st["bar"]
    b, seg = BARS[n], skel["bsegs"][n]
    pl, secs = [], []
    for s_no, (i, r, t, near) in enumerate(b["sec"]):
        j = b["joints"][i]
        q = JOINTS[j]
        where = "start" if s_no == 0 else "end" if s_no == len(b["sec"]) - 1 else f"section {s_no}"
        pname, sname = f"{st['name']} plane {where}", f"{st['name']} {where} section"
        p = section_plane(sw, seg, skel["points"][j], q, t, pname, checked=not FAST_PLANES, on=near)
        try:
            sec = circle_sketch(sw, p, q, r, seg, sname, normal=t, ways_max=1 if FAST_PLANES else 4)
        except OffPlane as ex:
            if not FAST_PLANES:
                raise
            print(f"  {pname}: {ex}; made again with the check")
            sw.model.ClearSelection2(True); p.Select2(False, 0); sw.model.Extension.DeleteSelection2(0)
            p = section_plane(sw, seg, skel["points"][j], q, t, pname, checked=True, on=near)
            sec = circle_sketch(sw, p, q, r, seg, sname, normal=t)
        pl.append(p); secs.append(sec)
        live_skeleton(sw, skel)
        seg = skel["bsegs"][n]
    made["planes"] += pl
    made["sketches"] += secs
    model = sw.model

    def loft(centerline):
        model.ClearSelection2(True)
        for k, sec in enumerate(secs):
            sec.Select2(k > 0, 1)
        if centerline:
            sd = call0(model.SelectionManager, "CreateSelectData"); sd.Mark = 4
            skel["bsegs"][n].Select4(True, sd)
        return model.FeatureManager.InsertProtrusionBlend2(False, True, False, 1.0, 0, 0, 1.0, 1.0, True, True, False,
                                                           0.0, 0.0, 0, True, True, True, 0)
    if not due(st):
        f = loft(True)
        if f is not None:
            f.Name = st["name"]
            print(f"{st['name']}: loft of {len(secs)} sections (checked with a later feature)")
            return
    ev, ec = expected(st, drift)
    tried = []
    for centerline in (True, False):
        variant = "spline as centerline" if centerline else "no centerline"
        live_skeleton(sw, skel)
        f = loft(centerline)
        if f is None:
            tried.append(f"{variant}: no loft"); continue
        v, c = checked_mass(sw, ev, tol(st))
        if abs(v - ev) <= tol(st):
            f.Name = st["name"]
            carry(drift, v, c, ev, ec)
            done_check(st)
            print(f"{st['name']}: loft of {len(secs)} sections, volume {v:.3f} mm^3 (expected {ev:.3f}; difference "
                  f"{v - ev:+.3f})" + (f" ({'; '.join(tried)})" if tried else ""))
            return
        tried.append(f"{variant}: volume {v:.3f}, expected {ev:.3f}")
        model.ClearSelection2(True); f.Select2(False, 0); model.Extension.DeleteSelection2(0)
    raise RuntimeError(f"{st['name']}: no loft gives the expected volume ({'; '.join(tried)})")


SW_FM_FILLET, SW_CONST_RADIUS = 1, 0     # swFeatureNameID_e.swFmFillet, swSimpleFilletType_e (sw_probe_bars, 2025)


def junction_edges(sw, pairs=False):
    """Edges between faces of two different Bar or Hub features; with pairs, grouped by the pair of features."""
    groups = {}
    for body in (sw.model.GetBodies2(0, True) or []):
        for e in call0(body, "GetEdges") or []:
            try:
                names = {call0(call0(f, "GetFeature"), "Name") for f in call0(e, "GetTwoAdjacentFaces2")}
            except Exception:
                continue
            if len(names) == 2 and all(nm.startswith(("Bar ", "Hub ")) for nm in names):
                groups.setdefault(tuple(sorted(names)), []).append(e)
    return groups if pairs else [e for es in groups.values() for e in es]


def fillet_edges(sw, edges, r):
    fm = sw.model.FeatureManager
    data = fm.CreateDefinition(SW_FM_FILLET)
    data.Initialize(SW_CONST_RADIUS)
    data.Edges = VARIANT(pythoncom.VT_ARRAY | pythoncom.VT_DISPATCH, edges)
    data.DefaultRadius = r * MM
    return fm.CreateFeature(data)


def fillet_step(sw, drift, made):
    """One fillet of radius R_FILLET on every edge where two bars, or a bar and a hub, meet (CreateDefinition: the
    only fillet call that worked over late binding, sw_probe_bars). If SolidWorks refuses all edges at once, one
    fillet per pair of features; a refused pair is reported. The volume it adds is carried to later checks."""
    v0, c0 = sw.mass_rebuilt()
    es = junction_edges(sw)
    if not es:
        print("junction fillet: no edges found"); return
    f = fillet_edges(sw, es, R_FILLET)
    done, skipped = len(es), []
    if f is not None:
        f.Name = "Junction fillet"
    else:
        done = 0
        for k, (pair, _) in enumerate(sorted(junction_edges(sw, pairs=True).items())):
            g = junction_edges(sw, pairs=True).get(pair)      # read again: edges change after each fillet
            if not g:
                continue
            f = fillet_edges(sw, g, R_FILLET)
            if f is None:
                skipped.append(" / ".join(pair))
            else:
                f.Name = f"Junction fillet {k + 1}"; done += len(g)
    v1, c1 = sw.mass_rebuilt()
    carry(drift, v1, c1, v0, c0)
    print(f"junction fillet r {R_FILLET:g} mm: {done} of {len(es)} edges, volume {v0:.3f} -> {v1:.3f} mm^3"
          + (f"; not filleted: {'; '.join(skipped)}" if skipped else ""))


PENDING = dict(n=0, tol=0.0)        # features since the last volume check, and their combined tolerance
LAST_OF_KIND = {}


def own_tol(st):
    return 0.01 * st["own"] + 1e-3 if st["kind"] in ("member", "bar") else 1e-3 * st["own"] + 1e-2


def due(st):
    """Whether this member or node is checked now: every CHECK_EVERY-th, and the last of its kind."""
    if CHECK_EVERY <= 1 or LAST_OF_KIND.get(st["kind"]) == st["name"] or PENDING["n"] + 1 >= CHECK_EVERY:
        return True
    PENDING["n"] += 1
    PENDING["tol"] += own_tol(st)
    return False


def tol(st):
    """Tolerance of a check: this feature's, plus those of the features since the last check."""
    return own_tol(st) + PENDING["tol"]


def done_check(st):
    PENDING["n"], PENDING["tol"] = 0, 0.0


def checked_mass(sw, expect, tol_):
    """Mass properties; with FAST_MASS read without forcing a rebuild, and read again after a rebuild when they do
    not match (so a stale value never fails a check)."""
    v, c = sw.mass()
    if FAST_MASS and abs(v - expect) > tol_:
        v, c = sw.mass_rebuilt()
    return v, c


